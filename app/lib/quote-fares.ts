  "5t": [81000, 84000, 100000, 105000, 110000, 115000, 130000, 135000, 138000, 145000, 148000, 150000, 152000, 156000, 158000, 160000, 170000, 175000, 180000, 185000, 195000, 199000, 205000, 208000, 210000, 215000, 218000, 220000, 223000],

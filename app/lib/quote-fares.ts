// 거리별 단가표로 예상 운임을 계산합니다 (거리톤수요율.xlsx "거리별단가표" 시트).

import { TONNAGE_OPTIONS } from "@/app/lib/quote-rates";

// 10km부터 5km 간격, 150km까지. 구간 값은 그 거리부터 다음 구간 전까지의 요금입니다.
const STEP_KM = 5;
const MIN_KM = 10;
const MAX_KM = 150;

/** 단가표 열: 1t, 2.5t, 3.5t, 5t, 8t, 11t (10km, 15km … 150km 순서) */
